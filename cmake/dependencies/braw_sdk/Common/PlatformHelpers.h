    inline NativeString NativeStringCopyUTF8(NativeString str) noexcept { return str ? SysAllocString(str) : nullptr; }

    inline NativeString NativeStringCopyUTF8(const char* str) noexcept
    {
        if (!str)
            return nullptr;

        const int wideCharCount = MultiByteToWideChar(CP_UTF8, 0, str, -1, nullptr, 0);

        BSTR strCopy = SysAllocStringLen(nullptr, wideCharCount);
        if (strCopy != nullptr)
            MultiByteToWideChar(CP_UTF8, 0, str, -1, strCopy, wideCharCount);

        return strCopy;
    }

    inline void NativeStringFree(NativeString str) noexcept
    {
        if (str)
            SysFreeString(str);
    }

    inline std::string NativeStringAsUTF8StdString(NativeString str) noexcept
    {
        if (!str)
            return {};

        const UINT strLength = SysStringLen(str);

        const int utf8Length = WideCharToMultiByte(CP_UTF8, 0, str, strLength, nullptr, 0, nullptr, nullptr);

        std::string utf8String(utf8Length, '\0');
        if (utf8Length > 0)
            WideCharToMultiByte(CP_UTF8, 0, str, strLength, utf8String.data(), utf8Length, nullptr, nullptr);

        return utf8String;
    }
#elif defined(__APPLE__)
    inline NativeString NativeStringCopyUTF8(NativeString str) noexcept
    {
        return str ? CFStringCreateCopy(kCFAllocatorDefault, str) : nullptr;
    }

    inline NativeString NativeStringCopyUTF8(const char* str) noexcept
    {
        return str ? CFStringCreateWithCString(kCFAllocatorDefault, str, kCFStringEncodingUTF8) : nullptr;
    }

    inline void NativeStringFree(NativeString str) noexcept
    {
        if (str)
        {
            assert(CFGetRetainCount(str) > 0);
            CFRelease(str);
        }
    }

    inline std::string NativeStringAsUTF8StdString(NativeString str) noexcept
    {
        const size_t length = CFStringGetLength(str);
        if (length == 0)
            return {};

        const CFIndex maxSize = CFStringGetMaximumSizeForEncoding(length, kCFStringEncodingUTF8) + 1;

        const char* utf8 = CFStringGetCStringPtr(str, kCFStringEncodingUTF8);
        if (utf8)
            return utf8;

        std::string utf8str(maxSize, '\0');
        CFStringGetCString(str, utf8str.data(), static_cast<CFIndex>(maxSize), kCFStringEncodingUTF8);
        return utf8str;
    }
