    class String
    {
    public:
        String() = default;

        ~String() { NativeStringFree(m_str); }

        explicit String(const char* str) noexcept
            : m_str(NativeStringCopyUTF8(str))
        {
        }

        template <typename T = NativeString, typename = std::enable_if_t<!std::is_same<T, const char*>::value>>
        explicit String(T str) noexcept
            : m_str(NativeStringCopyUTF8(str))
        {
        }

        String(const String&) noexcept = delete;
        String(String&&) noexcept = delete;

        String& operator=(const String&) noexcept = delete;
        String& operator=(String&&) noexcept = delete;

        operator NativeString() const noexcept { return m_str; }

        std::string str() const noexcept { return NativeStringAsUTF8StdString(m_str); }

        NativeString* outArg() noexcept
        {
            NativeStringFree(m_str);
            return &m_str;
        }

        NativeString release() noexcept { return std::exchange(m_str, nullptr); }

    private:
        NativeString m_str = {};
    };

