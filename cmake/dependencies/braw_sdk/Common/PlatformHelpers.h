    template <typename T> class OwningPtr
    {
    public:
        OwningPtr() = default;

        explicit OwningPtr(T* ptr)
            : m_ptr(ptr)
        {
            // We are not calling AddRef because we're only taking ownership
            // of a pointer that was created elsewhere as per COM semantics.
        }

        ~OwningPtr()
        {
            // We own this object now so Release must be called.
            if (m_ptr)
                m_ptr->Release();
        }

        OwningPtr(const OwningPtr&) = delete;
        OwningPtr& operator=(const OwningPtr&) = delete;

        OwningPtr(OwningPtr&& other)
            : m_ptr(std::exchange(other.m_ptr, nullptr))
        {
        }

        OwningPtr& operator=(OwningPtr&& other)
        {
            if (m_ptr)
                m_ptr->Release();

            m_ptr = std::exchange(other.m_ptr, nullptr);

            return *this;
        }

        T* operator->() const { return m_ptr; }

        operator T*() const { return m_ptr; }

        T** outArg()
        {
            assert(m_ptr == nullptr);
            return &m_ptr;
        }

    private:
        T* m_ptr = nullptr;
    };

