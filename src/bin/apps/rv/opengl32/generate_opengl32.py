"""Generate opengl32_functions.inc and opengl32.def for the opengl32.dll forwarder.

The forwarder exports every function the Windows opengl32.dll exports. The OpenGL 1.1 functions and
their signatures come from an OpenGL 1.1 GL/gl.h (the MinGW-w64 one, e.g. from zig or MSYS2); the WGL
and metafile entry points are listed below. Run it again only if that export list changes:

    python generate_opengl32.py path/to/GL/gl.h
"""

import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent

# opengl32.dll exports that are not in gl.h. Signatures from the Windows SDK (wingdi.h) and, for the
# undocumented ones GDI calls, from ReactOS.
EXTRA = [
    ("BOOL", "GlmfBeginGlsBlock", "HDC hdc"),
    ("BOOL", "GlmfCloseMetaFile", "HDC hdc"),
    ("BOOL", "GlmfEndGlsBlock", "HDC hdc"),
    ("BOOL", "GlmfEndPlayback", "HDC hdc"),
    ("BOOL", "GlmfInitPlayback", "HDC hdc, HENHMETAFILE hemf, LPRECTL rect"),
    ("BOOL", "GlmfPlayGlsRecord", "HDC hdc, DWORD id, BYTE* data, LPRECTL rect"),
    ("BOOL", "glDebugEntry", "DWORD a, DWORD b"),
    ("int", "wglChoosePixelFormat", "HDC hdc, const PIXELFORMATDESCRIPTOR* pfd"),
    ("BOOL", "wglCopyContext", "HGLRC src, HGLRC dst, UINT mask"),
    ("HGLRC", "wglCreateContext", "HDC hdc"),
    ("HGLRC", "wglCreateLayerContext", "HDC hdc, int layer"),
    ("BOOL", "wglDeleteContext", "HGLRC rc"),
    ("BOOL", "wglDescribeLayerPlane", "HDC hdc, int format, int layer, UINT bytes, LPLAYERPLANEDESCRIPTOR lpd"),
    ("int", "wglDescribePixelFormat", "HDC hdc, int format, UINT bytes, LPPIXELFORMATDESCRIPTOR pfd"),
    ("HGLRC", "wglGetCurrentContext", ""),
    ("HDC", "wglGetCurrentDC", ""),
    ("PROC", "wglGetDefaultProcAddress", "LPCSTR name"),
    ("int", "wglGetLayerPaletteEntries", "HDC hdc, int layer, int start, int count, COLORREF* colors"),
    ("int", "wglGetPixelFormat", "HDC hdc"),
    ("PROC", "wglGetProcAddress", "LPCSTR name"),
    ("BOOL", "wglMakeCurrent", "HDC hdc, HGLRC rc"),
    ("BOOL", "wglRealizeLayerPalette", "HDC hdc, int layer, BOOL realize"),
    ("int", "wglSetLayerPaletteEntries", "HDC hdc, int layer, int start, int count, const COLORREF* colors"),
    ("BOOL", "wglSetPixelFormat", "HDC hdc, int format, const PIXELFORMATDESCRIPTOR* pfd"),
    ("BOOL", "wglShareLists", "HGLRC a, HGLRC b"),
    ("BOOL", "wglSwapBuffers", "HDC hdc"),
    ("BOOL", "wglSwapLayerBuffers", "HDC hdc, UINT planes"),
    ("DWORD", "wglSwapMultipleBuffers", "UINT count, const WGLSWAP* swaps"),
    ("BOOL", "wglUseFontBitmapsA", "HDC hdc, DWORD first, DWORD count, DWORD base"),
    ("BOOL", "wglUseFontBitmapsW", "HDC hdc, DWORD first, DWORD count, DWORD base"),
    (
        "BOOL",
        "wglUseFontOutlinesA",
        "HDC hdc, DWORD first, DWORD count, DWORD base, FLOAT deviation, FLOAT extrusion, int format, LPGLYPHMETRICSFLOAT gmf",
    ),
    (
        "BOOL",
        "wglUseFontOutlinesW",
        "HDC hdc, DWORD first, DWORD count, DWORD base, FLOAT deviation, FLOAT extrusion, int format, LPGLYPHMETRICSFLOAT gmf",
    ),
]

PROTOTYPE = re.compile(r"^\s*WINGDIAPI\s+(.+?)\s*APIENTRY\s+(gl\w+)\s*\((.*)\)\s*;")


def param_names(params):
    params = params.strip()
    if params in ("", "void"):
        return []
    names = []
    for param in params.split(","):
        match = re.search(r"(\w+)\s*(\[\s*\d*\s*\])?\s*$", param.strip())
        if not match:
            sys.exit(f"cannot find the parameter name in '{param}'")
        names.append(match.group(1))
    return names


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    functions = []
    for line in pathlib.Path(sys.argv[1]).read_text().splitlines():
        match = PROTOTYPE.match(line)
        if match:
            ret, name, params = match.groups()
            functions.append((ret.strip(), name, params.strip()))
    if len(functions) != 336:
        sys.exit(f"expected the 336 OpenGL 1.1 functions, found {len(functions)}")
    functions += EXTRA
    functions.sort(key=lambda f: f[1])

    lines = [
        "//",
        "// Generated by generate_opengl32.py. Do not edit.",
        "//",
        "// OPENGL32_FUNCTION(return type, name, (parameters), (arguments))",
        "//",
    ]
    for ret, name, params in functions:
        args = ", ".join(param_names(params))
        lines.append(f"OPENGL32_FUNCTION({ret}, {name}, ({params if params else 'void'}), ({args}))")
    (HERE / "opengl32_functions.inc").write_text("\n".join(lines) + "\n", newline="\n")

    exports = ["; Generated by generate_opengl32.py. Do not edit.", "LIBRARY opengl32", "EXPORTS"]
    exports += [f"    {name} = utv_{name}" for _, name, _ in functions]
    (HERE / "opengl32.def").write_text("\n".join(exports) + "\n", newline="\n")
    print(f"{len(functions)} functions")


if __name__ == "__main__":
    main()
